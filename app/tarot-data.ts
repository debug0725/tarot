function memeIndex(major: DrawnCard, minor: DrawnCard, category: Category, length: number) {
  const seed = `${major.card.id}|${major.orientation}|${minor.card.id}|${minor.orientation}|${category}`;
  return [...seed].reduce((total, character) => total + character.charCodeAt(0), 0) % length;
}

