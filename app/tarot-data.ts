export function readingFor(category: Category, major: DrawnCard, minor: DrawnCard, question = ""): DetailedReading {
  const majorMeaning = major.card[major.orientation];
  const minorMeaning = minor.card[minor.orientation];
  const suitKey = minor.card.suit as Suit;
  const score = majorMeaning.score + minorMeaning.score;
  const band = scoreBand(score);
  const focus = detectQuestionFocus(question, category);
  const intent = focus.intent;
  const patternKey = `${major.orientation}-${minor.orientation}`;
  const rank = rankSignals[minor.card.number] ?? rankSignals.P;
  const directAnswer = contextualAnswer(focus, category, band, major, minor);
  const combinationNote = `${orientationPatterns[patternKey]} ${categoryPulse[category][band]}`;
  const behavior = `${minorMeaning.text} ${rank.behavior} ${suitBehavior(suitKey, minor.orientation, category)}`;
  const obstacle = `${major.orientation === "reversed" ? majorMeaning.text : `이 흐름의 그림자에는 ${majorMeaning.keywords}가 과해질 때 생기는 부담이 있습니다.`} ${rank.caution}`;
  const nearFuture = `${categoryPulse[category][band]} ${minor.orientation === "upright" ? `가까운 변화는 ${minor.card.name}처럼 구체적인 행동에서 먼저 확인됩니다.` : `다만 ${minor.card.name} 역방향이므로 말과 행동이 한 차례 어긋날 수 있어 반복 여부를 봐야 합니다.`}`;
  const advice = `${majorMeaning.advice} 이어서 ${minorMeaning.advice} 두 조언을 함께 적용하면 감정에 끌려가기보다 확인 가능한 행동을 기준으로 선택할 수 있습니다.`;
  const actionPlan = actionPlanFor(category, band, major, minor);

  return {
    score,
    verdict: verdicts[category][band],
    intent,
    intentLabel: focus.label || intentLabels[intent],
    answerTag: answerTags[category][band],
    directAnswer,
    answerEvidence: `${major.card.name}${major.orientation === "reversed" ? " 역방향" : " 정방향"}은 관계의 큰 방향을, ${minor.card.name}${minor.orientation === "reversed" ? " 역방향" : " 정방향"}은 실제 연락과 행동의 상태를 보여줍니다.`,
    answerCheck: actionPlan.observe,
    overview: `${major.card.name}${major.orientation === "reversed" ? " 역방향" : " 정방향"}은 ${majorMeaning.text} ${minor.card.name}${minor.orientation === "reversed" ? " 역방향" : " 정방향"}은 ${minorMeaning.text}`,
    combinationNote,
    cardSections: [
      { title: category === "love" ? "이 관계를 이끄는 큰 흐름" : category === "reunion" ? "두 사람 사이에 남은 큰 흐름" : "이별이 남긴 큰 의미", body: `${majorMeaning.text} ${major.card.name}의 ${majorMeaning.keywords}가 이번 질문의 바탕에 놓여 있습니다.` },
      { title: category === "love" ? "지금 실제 감정과 행동" : category === "reunion" ? "연락과 재회에 필요한 현실" : "지금 회복을 돕는 현실", body: `${minorMeaning.text} ${suitMeta[suitKey].lens[category]}` },
    ],
    detailSections: [
      { label: "01 · CARD COMBINATION", title: "두 카드가 함께 보이는 관계", body: combinationNote },
      { label: "02 · VISIBLE BEHAVIOR", title: category === "breakup" ? "감정이 생활에서 드러나는 방식" : "상대가 겉으로 보일 태도", body: behavior },
      { label: "03 · HIDDEN BLOCK", title: category === "breakup" ? "회복을 더디게 만드는 지점" : "관계를 막는 핵심 지점", body: obstacle },
      { label: "04 · NEAR FLOW", title: category === "breakup" ? "가까운 회복의 흐름" : "가까운 시기의 흐름", body: nearFuture },
    ],
    timing: timingFor(category, suitKey, minor.orientation, band),
    actionPlan,
    memberPlay: memberPlayFor(category, intent, band, major, minor),
    advice,
    keywords: `${majorMeaning.keywords} × ${minorMeaning.keywords}`,
  };
}
